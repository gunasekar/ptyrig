const vscode = require('vscode');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn) { for(let i=0;i<100;i++) { if(fn()) return; await wait(50); } throw new Error('Timed out'); }
exports.run = async () => {
  try {
    const extension = vscode.extensions.all.find(e => e.packageJSON.name === 'ptyrig');
    // Startup must expose the launcher without a command or explicit activation.
    await until(() => extension.isActive);
    const api = extension.exports;
    assert.equal(api.getSessions().length,0);
    const config = vscode.workspace.getConfiguration('ptyrig');
    await config.update('command', 'sleep 120', vscode.ConfigurationTarget.Workspace);
    await config.update('sessionTitle','Trails',vscode.ConfigurationTarget.Workspace);
    const document = await vscode.workspace.openTextDocument({content:'Keep this editor separate'});
    await vscode.window.showTextDocument(document);
    const terminalCount = vscode.window.terminals.length;
    await vscode.commands.executeCommand('ptyrig.toggle');
    await until(() => api.getSessions().some(s => s.visible && s.rendererReady && s.renderedFrames > 0));
    await vscode.commands.executeCommand('ptyrig.new');
    await until(() => api.getSessions().length === 2);
    await until(() => api.getSessions().some(s => s.visible && s.rendererReady && s.renderedFrames > 0));
    const pids = api.getSessions().map(s => s.pid);
    assert.deepEqual(api.getSessions().map(s => s.title),['1: Trails','2: Trails']);
    for (let i=0;i<3;i++) {
      // Selecting the first tab used to recreate it last on the next show.
      await vscode.commands.executeCommand('workbench.action.firstEditorInGroup');
      await until(() => vscode.window.tabGroups.activeTabGroup.activeTab?.label === '1: Trails');
      await vscode.commands.executeCommand('ptyrig.toggle');
      assert.equal(api.getSessions().some(s => s.visible),false);
      await until(() => vscode.window.tabGroups.all.flatMap(g=>g.tabs).filter(t=>t.input instanceof vscode.TabInputWebview).length === 0);
      for(const pid of pids) process.kill(pid,0);
      await vscode.commands.executeCommand('ptyrig.toggle');
      await until(() => api.getSessions().some(s => s.visible && s.rendererReady && s.renderedFrames > 0));
      assert.deepEqual(api.getSessions().map(s=>s.pid),pids);
      const groups = vscode.window.tabGroups.all.filter(g=>g.tabs.some(t=>t.input instanceof vscode.TabInputWebview));
      assert.equal(groups.length,1);
      assert.equal(groups[0].tabs.filter(t=>t.input instanceof vscode.TabInputWebview).length,2);
      assert.deepEqual(groups[0].tabs.map(t=>t.label), ['1: Trails','2: Trails']);
      await until(() => groups[0].activeTab?.label === '1: Trails');
      assert.equal(groups[0].tabs.some(t=>t.input instanceof vscode.TabInputText),false);
      assert.equal(vscode.window.terminals.length,terminalCount);
    }
    await vscode.commands.executeCommand('moveActiveEditor', {to:'last', by:'tab'});
    await until(() => vscode.window.tabGroups.activeTabGroup.tabs[0]?.label === '2: Trails');
    await vscode.commands.executeCommand('ptyrig.toggle');
    await vscode.commands.executeCommand('ptyrig.toggle');
    await until(() => vscode.window.tabGroups.activeTabGroup.tabs.length === 2);
    assert.deepEqual(vscode.window.tabGroups.activeTabGroup.tabs.map(t=>t.label), ['2: Trails','1: Trails']);
    await until(() => vscode.window.tabGroups.activeTabGroup.activeTab?.label === '1: Trails');
    const tabs = vscode.window.tabGroups.all.flatMap(g=>g.tabs).filter(t=>t.input instanceof vscode.TabInputWebview);
    await vscode.window.tabGroups.close(tabs);
    await until(()=>api.getSessions().length===0);
    await config.update('multipleSessions', false, vscode.ConfigurationTarget.Workspace);
    await vscode.commands.executeCommand('ptyrig.new');
    await until(() => api.getSessions().some(s => s.rendererReady && s.renderedFrames > 0));
    const single = api.getSessions()[0];
    assert.equal(single.title, 'Trails');
    await Promise.all(Array.from({length:3}, () => vscode.commands.executeCommand('ptyrig.new')));
    assert.equal(api.getSessions().length, 1);
    assert.equal(api.getSessions()[0].pid, single.pid);
    await vscode.commands.executeCommand('ptyrig.toggle');
    assert.equal(api.getSessions()[0].visible, false);
    await vscode.commands.executeCommand('ptyrig.new');
    await until(() => api.getSessions()[0].visible);
    assert.equal(api.getSessions()[0].pid, single.pid);
    await config.update('multipleSessions', true, vscode.ConfigurationTarget.Workspace);
    await vscode.commands.executeCommand('ptyrig.new');
    assert.equal(api.getSessions().length, 2);
    assert.match(api.getSessions()[1].title, /^\d+: Trails$/);
    const preserved = api.getSessions().map(s=>s.pid);
    await config.update('multipleSessions', false, vscode.ConfigurationTarget.Workspace);
    await vscode.commands.executeCommand('ptyrig.new');
    assert.deepEqual(api.getSessions().map(s=>s.pid), preserved);
    await vscode.window.tabGroups.close(vscode.window.tabGroups.all.flatMap(g=>g.tabs).filter(t=>t.input instanceof vscode.TabInputWebview));
    await until(()=>api.getSessions().length===0);
    await vscode.commands.executeCommand('ptyrig.new');
    assert.equal(api.getSessions().length,1);
    assert.equal(api.getSessions()[0].title,'Trails');
    assert.notEqual(api.getSessions()[0].pid,single.pid);
    await vscode.window.tabGroups.close(vscode.window.tabGroups.all.flatMap(g=>g.tabs).filter(t=>t.input instanceof vscode.TabInputWebview));
    await until(()=>api.getSessions().length===0);
    await config.update('sessionTitle','Agent ($CMD)',vscode.ConfigurationTarget.Workspace);
    await config.update('command',"printf '\\033]777;ptyrig-command;codex\\007'; sleep 1; printf '\\033]777;ptyrig-command;claude\\007'; sleep 120",vscode.ConfigurationTarget.Workspace);
    await vscode.commands.executeCommand('ptyrig.new');
    await until(()=>api.getSessions()[0]?.title==='Agent (codex)');
    await vscode.commands.executeCommand('ptyrig.toggle');
    await until(()=>api.getSessions()[0]?.title==='Agent (claude)');
    await vscode.commands.executeCommand('ptyrig.toggle');
    await until(()=>vscode.window.tabGroups.all.some(g=>g.tabs.some(t=>t.label==='Agent (claude)')));
    await vscode.window.tabGroups.close(vscode.window.tabGroups.all.flatMap(g=>g.tabs).filter(t=>t.input instanceof vscode.TabInputWebview));
    await until(()=>api.getSessions().length===0);
    await config.update('command','exit 7',vscode.ConfigurationTarget.Workspace);
    await vscode.commands.executeCommand('ptyrig.new');
    await until(()=>api.getSessions().length===0);
    fs.writeFileSync(process.env.PTYRIG_TEST_RESULT,'PASS: startup activation without process launch, real VS Code native PTY, multi-session hide/show, stable and manually reordered tabs, selected session, grouped views, process IDs, numbered titles, single-session reuse, mode changes, dynamic command titles and exit cleanup');
  } catch(error) { fs.writeFileSync(process.env.PTYRIG_TEST_RESULT,`FAIL: ${error.stack}`); throw error; }
};
